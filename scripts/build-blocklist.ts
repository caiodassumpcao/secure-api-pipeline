/**
 * Regenerates src/modules/auth/blocklist.ts from a list of common passwords,
 * one per line. The committed module was built from SecLists
 * Passwords/Common-Credentials/Pwdb_top-100000.txt (MIT licence):
 *
 *   node scripts/build-blocklist.ts Pwdb_top-100000.txt
 *
 * Entries are normalized like passwords (NFKC, then lower-cased), and only
 * those of 12 to 128 characters are kept: the length rule rejects the others.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import {
  codePointLength,
  PASSWORD_MAX_LENGTH,
  PASSWORD_MIN_LENGTH,
} from '../src/modules/auth/password-rules.ts';

const OUTPUT = new URL('../src/modules/auth/blocklist.ts', import.meta.url);

export function buildBlocklist(source: string): string[] {
  const entries = new Set<string>();
  for (const line of source.split(/\r?\n/)) {
    const entry = line.normalize('NFKC').toLowerCase();
    const length = codePointLength(entry);
    // Printable entries only: no control or format characters, no backticks
    // or `${` that would end the template literal of the module.
    if (length < PASSWORD_MIN_LENGTH || length > PASSWORD_MAX_LENGTH) continue;
    if (/[\p{C}`\\]|\$\{/u.test(entry)) continue;
    entries.add(entry);
  }
  return [...entries];
}

if (import.meta.main) {
  const [file] = process.argv.slice(2);
  if (file === undefined) {
    process.stderr.write('usage: node scripts/build-blocklist.ts <list.txt>\n');
    process.exit(1);
  }
  // The path comes from the developer's command line.
  // eslint-disable-next-line security/detect-non-literal-fs-filename
  const entries = buildBlocklist(readFileSync(file, 'utf8'));
  const module = `/**
 * Common passwords of ${PASSWORD_MIN_LENGTH} to ${PASSWORD_MAX_LENGTH} characters, which the length rule alone
 * would accept (NIST SP 800-63B: reject passwords known from breaches).
 * Generated by scripts/build-blocklist.ts from SecLists
 * Passwords/Common-Credentials/Pwdb_top-100000.txt (MIT licence). Do not edit.
 */
const ENTRIES = \`${entries.join('\n')}\`;

/** NFKC-normalized, lower-cased entries. */
export const BLOCKLIST: ReadonlySet<string> = new Set(ENTRIES.split('\\n'));
`;
  // Fixed path inside the repository.
  // eslint-disable-next-line security/detect-non-literal-fs-filename
  writeFileSync(OUTPUT, module);
  process.stdout.write(`${entries.length} entries written to src/modules/auth/blocklist.ts\n`);
}
